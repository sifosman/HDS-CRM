export async function getDashboardStats() {
  const supabase = await createClient();

  const [customersRes, quotesRes, conversationsRes] = await Promise.all([
    supabase.from("customer_profiles").select("*").or("do_not_contact.is.false,do_not_contact.is.null"),
    supabase.from("quotes").select("total, created_at, status, source"),
    supabase
      .from("ai_conversations")
      .select("id, phone_number, sender_name, role, message_text, lead_status, created_at")
      .order("created_at", { ascending: false })
      .limit(10),
  ]);

  const customers = (customersRes.data || []) as CustomerProfile[];
  const quotes = (quotesRes.data || []) as Pick<
    Quote,
    "total" | "created_at" | "status" | "source"
  >[];
  const recentActivity = (conversationsRes.data || []) as Pick<
    Conversation,
    "id" | "phone_number" | "sender_name" | "role" | "message_text" | "lead_status" | "created_at"
  >[];

  // Split quotes by source for chatbot-first reporting
  const chatbotQuotes = quotes.filter((q) => q.source === "chatbot");

  // Chatbot-first metrics (primary)
  const chatbotRevenue = chatbotQuotes.reduce((sum, q) => sum + Number(q.total || 0), 0);

  // Customer-accepted quotes (derived from conversation analysis + lead stage).
  // Fetch full chatbot quote rows (need id/customer_phone/created_at/source)
  // and run the acceptance derivation used on the quotes page.
  const fullChatbotQuotes = await getChatbotQuotes();
  const acceptance = await getChatbotQuoteAcceptance(fullChatbotQuotes);
  const acceptedQuotes = fullChatbotQuotes.filter(
    (q) => acceptance[q.id]?.accepted
  );
  const acceptedQuotesCount = acceptedQuotes.length;
  const acceptedQuotesValue = acceptedQuotes.reduce(
    (sum, q) => sum + Number(q.total || 0),
    0
  );
  const activeLeads = customers.filter(
    (c) => c.lead_status !== "closed" && c.lead_status !== "lost"
  ).length;

  const now = new Date();
  const weekAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
  const chatbotQuotesThisWeek = chatbotQuotes.filter(
    (q) => new Date(q.created_at) >= weekAgo
  ).length;

  // Quote conversion rate = customer-accepted quotes / total chatbot quotes.
  // Measures what percentage of quotes generated by the chatbot were actually
  // accepted by customers (via message keyword or lead stage progression).
  const conversionRate =
    fullChatbotQuotes.length > 0
      ? Math.round((acceptedQuotesCount / fullChatbotQuotes.length) * 100)
      : 0;

  // Pipeline stages
  const pipeline = [
    "new",
    "quoting",
    "quoted",
    "closing",
    "objection",
    "follow_up",
    "handover",
    "closed",
  ].map((stage) => ({
    stage,
    count: customers.filter((c) => c.lead_status === stage).length,
  }));

  // Monthly revenue (last 6 months) — chatbot only
  const monthlyRevenue: { month: string; revenue: number }[] = [];
  for (let i = 5; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    const monthEnd = new Date(now.getFullYear(), now.getMonth() - i + 1, 0);
    const monthName = d.toLocaleString("en-ZA", { month: "short" });
    const revenue = chatbotQuotes
      .filter((q) => {
        const qd = new Date(q.created_at);
        return qd >= d && qd <= monthEnd;
      })
      .reduce((sum, q) => sum + Number(q.total || 0), 0);
    monthlyRevenue.push({ month: monthName, revenue });
  }

  return {
    // Chatbot-first (primary metrics)
    totalRevenue: chatbotRevenue,
    activeLeads,
    quotesThisWeek: chatbotQuotesThisWeek,
    conversionRate,
    totalCustomers: customers.length,
    pipeline,
    monthlyRevenue,
    recentActivity,
    // Customer-accepted quotes (derived)
    acceptedQuotesCount,
    acceptedQuotesValue,
    totalQuotes: fullChatbotQuotes.length,
  };
}

