/**
 * Get per-category pass rates aggregated across recent runs.
 * Returns one entry per category with total/passed/failed counts and pass rate.
 *
 * IMPORTANT: Only aggregates across runs that actually test each category.
 * Smoke runs cover all 9 core categories (1 scenario each), so they're the
 * most reliable source for cross-category comparison. Category runs only test
 * one category (e.g. 40 new_customer scenarios), so including them would
 * heavily skew the aggregation. We prefer smoke runs, falling back to any
 * run type if no smoke runs exist.
 */
export async function getAiTestCategoryStats(
  runsLimit = 5
): Promise<
  Array<{
    category: string;
    total: number;
    passed: number;
    failed: number;
    passRate: number;
    avgLatencyMs: number | null;
    runCount: number;
  }>
> {
  const supabase = await createClient();

  // Prefer smoke runs (they cover all core categories evenly).
  // Fall back to any run type if not enough smoke runs exist.
  let runIds: string[] = [];

  const { data: smokeRuns } = await supabase
    .from("ai_test_run_summaries")
    .select("run_id")
    .eq("run_type", "smoke")
    .order("created_at", { ascending: false })
    .limit(runsLimit);

  runIds = (smokeRuns || []).map((r) => r.run_id);

  // If fewer than 3 smoke runs, supplement with full runs
  if (runIds.length < 3) {
    const { data: fullRuns } = await supabase
      .from("ai_test_run_summaries")
      .select("run_id")
      .eq("run_type", "full")
      .order("created_at", { ascending: false })
      .limit(runsLimit - runIds.length);
    runIds = [...runIds, ...(fullRuns || []).map((r) => r.run_id)];
  }

  // If still no runs, fall back to any recent runs
  if (runIds.length === 0) {
    const { data: anyRuns } = await supabase
      .from("ai_test_run_summaries")
      .select("run_id")
      .order("created_at", { ascending: false })
      .limit(runsLimit);
    runIds = (anyRuns || []).map((r) => r.run_id);
  }

  if (runIds.length === 0) {
    return TEST_CATEGORY_ORDER.map((category) => ({
      category,
      total: 0,
      passed: 0,
      failed: 0,
      passRate: 0,
      avgLatencyMs: null,
      runCount: 0,
    }));
  }

  // Fetch all test runs for those run_ids
  const { data, error } = await supabase
    .from("ai_test_runs")
    .select("category, passed, latency_ms, run_id")
    .in("run_id", runIds);

  if (error) throw error;

  const runs = data || [];
  const contributingRunIds = new Set(runIds);

  // Build stats per category, including any categories with zero results
  const allCategories = new Set<string>(TEST_CATEGORY_ORDER);
  for (const r of runs) allCategories.add(r.category);

  return Array.from(allCategories).map((category) => {
    const catRuns = runs.filter((r) => r.category === category);
    const total = catRuns.length;
    const passed = catRuns.filter((r) => r.passed).length;
    const failed = total - passed;
    const passRate = total > 0 ? Math.round((passed / total) * 100) : 0;
    const latencies = catRuns
      .filter((r) => r.latency_ms != null)
      .map((r) => r.latency_ms as number);
    const avgLatencyMs =
      latencies.length > 0
        ? Math.round(latencies.reduce((a, b) => a + b, 0) / latencies.length)
        : null;
    // Count how many of the contributing runs actually tested this category
    const catRunIds = new Set(catRuns.map((r) => r.run_id));
    const runCount = Array.from(contributingRunIds).filter((id) =>
      catRunIds.has(id)
    ).length;
    return { category, total, passed, failed, passRate, avgLatencyMs, runCount };
  });
}

/**
 * Get latency distribution buckets for the most recent run.
 * Returns counts per latency bucket for histogram-style display.
 */
export async function getAiTestLatencyDistribution(
  runId?: string
): Promise<Array<{ bucket: string; count: number }>> {
  const supabase = await createClient();

  let query = supabase
    .from("ai_test_runs")
    .select("latency_ms")
    .not("latency_ms", "is", null);

  if (runId) {
    query = query.eq("run_id", runId);
  } else {
    // Use the latest non-scenario run (scenario runs have only 1 test,
    // which produces a useless single-bar histogram)
    const { data: latest } = await supabase
      .from("ai_test_run_summaries")
      .select("run_id")
      .in("run_type", ["smoke", "category", "full"])
      .order("created_at", { ascending: false })
      .limit(1)
      .single();
    if (!latest) {
      return [];
    }
    query = query.eq("run_id", latest.run_id);
  }

  const { data, error } = await query;
  if (error) throw error;

  const latencies = (data || []).map((r) => r.latency_ms as number);

  const buckets = [
    { bucket: "0-5s", min: 0, max: 5000, count: 0 },
    { bucket: "5-10s", min: 5000, max: 10000, count: 0 },
    { bucket: "10-20s", min: 10000, max: 20000, count: 0 },
    { bucket: "20-30s", min: 20000, max: 30000, count: 0 },
    { bucket: "30-45s", min: 30000, max: 45000, count: 0 },
    { bucket: "45s+", min: 45000, max: Infinity, count: 0 },
  ];

  for (const lat of latencies) {
    for (const b of buckets) {
      if (lat >= b.min && lat < b.max) {
        b.count++;
        break;
      }
    }
  }

  return buckets.map(({ bucket, count }) => ({ bucket, count }));
}

/**
 * Get scenario failure frequency — which scenarios fail most often across
 * recent runs. Helps identify persistently broken scenarios vs flaky ones.
 */
export async function getAiTestFailureFrequency(
  runsLimit = 10
): Promise<
  Array<{
    scenario_id: string;
    scenario_name: string | null;
    category: string;
    failCount: number;
    lastFailedAt: string;
  }>
> {
  const supabase = await createClient();

  // Get recent run_ids
  const { data: runData } = await supabase
    .from("ai_test_run_summaries")
    .select("run_id")
    .order("created_at", { ascending: false })
    .limit(runsLimit);

  const runIds = (runData || []).map((r) => r.run_id);
  if (runIds.length === 0) return [];

  const { data, error } = await supabase
    .from("ai_test_runs")
    .select("scenario_id, scenario_name, category, created_at")
    .eq("passed", false)
    .in("run_id", runIds)
    .order("created_at", { ascending: false });

  if (error) throw error;

  const runs = data || [];
  const byScenario = new Map<
    string,
    { scenario_name: string | null; category: string; failCount: number; lastFailedAt: string }
  >();

  for (const r of runs) {
    const existing = byScenario.get(r.scenario_id);
    if (existing) {
      existing.failCount++;
      if (r.created_at > existing.lastFailedAt) {
        existing.lastFailedAt = r.created_at;
      }
    } else {
      byScenario.set(r.scenario_id, {
        scenario_name: r.scenario_name,
        category: r.category,
        failCount: 1,
        lastFailedAt: r.created_at,
      });
    }
  }

  return Array.from(byScenario.entries())
    .map(([scenario_id, val]) => ({ scenario_id, ...val }))
    .sort((a, b) => b.failCount - a.failCount);
}

