/**
 * Build a per-customer quote breakdown (converted / pending / sent) by
 * merging two data sources:
 *
 *  1. `quotes` table joined with `invoices` — quotes that flowed through the
 *     Vercel quote engine and have a `customer_phone`. A quote is:
 *       - converted → has at least one paid invoice
 *       - pending   → has a pending invoice (no paid invoice)
 *       - sent      → no invoice yet
 *
 *  2. `ai_conversations` — quotes generated by the WhatsApp AI chatbot. Each
 *     distinct `quote_id` per phone represents one quote. These are
 *     categorised as "sent" unless the customer's `payment_status` on
 *     `customer_profiles` is `paid` (in which case one quote is marked
 *     converted) or `partial` / `pending` (one quote marked pending).
 *
 * Phone numbers are normalised by stripping a leading "+" so that
 * "+27123456789" and "27123456789" are treated as the same customer.
 */
export async function getCustomerQuoteBreakdown(): Promise<CustomerQuoteBreakdownMap> {
  const supabase = await createClient();

  // Fetch quotes that have a customer_phone, plus all invoices.
  const [quotesRes, invoicesRes, convRes, customersRes] = await Promise.all([
    supabase
      .from("quotes")
      .select("id, customer_phone, status")
      .not("customer_phone", "is", null),
    supabase.from("invoices").select("quote_id, status"),
    supabase
      .from("ai_conversations")
      .select("phone_number, quote_id")
      .not("quote_id", "is", null),
    supabase
      .from("customer_profiles")
      .select("phone_number, payment_status"),
  ]);

  const map: CustomerQuoteBreakdownMap = {};
  const ensure = (phone: string): CustomerQuoteBreakdown => {
    const key = phone.replace(/^\+/, "");
    if (!map[key]) {
      map[key] = { converted: 0, pending: 0, sent: 0, total: 0 };
    }
    return map[key];
  };

  // 1. Quotes table + invoices join
  const quotes = (quotesRes.data || []) as {
    id: string;
    customer_phone: string | null;
    status: string | null;
  }[];
  const invoices = (invoicesRes.data || []) as {
    quote_id: string | null;
    status: string | null;
  }[];

  // Build quote_id → invoice statuses
  const invoicesByQuote = new Map<string, string[]>();
  for (const inv of invoices) {
    if (!inv.quote_id) continue;
    const arr = invoicesByQuote.get(inv.quote_id) || [];
    arr.push(inv.status || "pending");
    invoicesByQuote.set(inv.quote_id, arr);
  }

  // Track which (phone, quote_id) pairs we've already counted from the quotes
  // table so we don't double-count them from ai_conversations.
  const countedFromQuotes = new Set<string>();

  for (const q of quotes) {
    if (!q.customer_phone) continue;
    const stats = ensure(q.customer_phone);
    const invStatuses = invoicesByQuote.get(q.id) || [];
    if (invStatuses.includes("paid")) {
      stats.converted += 1;
    } else if (invStatuses.includes("pending")) {
      stats.pending += 1;
    } else {
      stats.sent += 1;
    }
    stats.total += 1;
    countedFromQuotes.add(`${q.customer_phone.replace(/^\+/, "")}:${q.id}`);
  }

  // 2. AI conversations — count distinct quote_ids per phone
  const convs = (convRes.data || []) as {
    phone_number: string | null;
    quote_id: string | null;
  }[];
  const customers = (customersRes.data || []) as {
    phone_number: string | null;
    payment_status: string | null;
  }[];
  const paymentByPhone = new Map<string, string | null>();
  for (const c of customers) {
    if (c.phone_number) {
      paymentByPhone.set(c.phone_number.replace(/^\+/, ""), c.payment_status);
    }
  }

  // Distinct quote_ids per phone from conversations
  const aiQuotesByPhone = new Map<string, Set<string>>();
  for (const c of convs) {
    if (!c.phone_number || !c.quote_id) continue;
    const phone = c.phone_number.replace(/^\+/, "");
    if (!aiQuotesByPhone.has(phone)) {
      aiQuotesByPhone.set(phone, new Set());
    }
    aiQuotesByPhone.get(phone)!.add(c.quote_id);
  }

  for (const [phone, quoteIds] of aiQuotesByPhone) {
    const stats = ensure(phone);
    const paymentStatus = paymentByPhone.get(phone);
    let convertedFromAI = 0;
    let pendingFromAI = 0;
    if (paymentStatus === "paid") {
      convertedFromAI = 1; // at least one quote converted
    } else if (paymentStatus === "partial" || paymentStatus === "pending") {
      pendingFromAI = 1;
    }
    const sentFromAI = Math.max(0, quoteIds.size - convertedFromAI - pendingFromAI);
    stats.converted += convertedFromAI;
    stats.pending += pendingFromAI;
    stats.sent += sentFromAI;
    stats.total += quoteIds.size;
  }

  return map;
}

